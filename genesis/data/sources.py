"""Source registry: every corpus enters the pipeline with its rights recorded.

A registry is a JSON file with a list of sources (see
``configs/sources.example.json``). The pipeline refuses sources whose license
or rights basis is missing, so provenance cannot be silently dropped. The
registry records what *you* assert; it cannot verify that the assertion is
true. Legal review stays a human responsibility.
"""
from __future__ import annotations

from dataclasses import asdict, dataclass, field
import glob
import os
import gzip
import io
import json
from pathlib import Path
from typing import Iterator

RIGHTS_BASES = {
    "self-authored",           # you wrote it
    "open-license",            # e.g. CC BY, CC BY-SA, ODC-By, Apache-2.0, MIT
    "public-domain",           # expired copyright or dedicated to public domain
    "statutory-unprotected",   # e.g. Korean Copyright Act Art. 7: statutes, court rulings
    "public-sector-license",   # e.g. KOGL (공공누리) Type 1
    "contract",                # signed agreement / purchased license
    "synthetic",               # generated by a model whose terms allow training use
}
SOURCE_TYPES = {"txt", "jsonl", "parquet"}
DOC_SPLITS = {"file", "paragraph", "line"}


@dataclass(frozen=True)
class SourceSpec:
    name: str
    type: str
    path: str
    license: str
    rights_basis: str
    language: str = "ko"              # ko | en | mixed | code | any
    text_field: str = "text"
    id_field: str | None = None
    doc_split: str = "file"           # txt only
    license_url: str | None = None
    attribution: str | None = None
    commercial_use: str = "unknown"   # yes | no | unknown
    notes: str | None = None
    max_docs: int | None = None
    filters: dict = field(default_factory=dict)

    def __post_init__(self) -> None:
        if not self.name.strip():
            raise ValueError("source name is required")
        if self.type not in SOURCE_TYPES:
            raise ValueError(f"{self.name}: type must be one of {sorted(SOURCE_TYPES)}")
        if not self.license.strip() or self.license.strip().lower() in {"unknown", "none", "?"}:
            raise ValueError(f"{self.name}: a concrete license is required (got {self.license!r})")
        if self.rights_basis not in RIGHTS_BASES:
            raise ValueError(f"{self.name}: rights_basis must be one of {sorted(RIGHTS_BASES)}")
        if self.doc_split not in DOC_SPLITS:
            raise ValueError(f"{self.name}: doc_split must be one of {sorted(DOC_SPLITS)}")
        if self.commercial_use not in {"yes", "no", "unknown"}:
            raise ValueError(f"{self.name}: commercial_use must be yes, no or unknown")

    def provenance(self) -> dict:
        data = asdict(self)
        data.pop("filters")
        data.pop("max_docs")
        return data


def load_registry(path: str | Path) -> list[SourceSpec]:
    raw = json.loads(Path(path).read_text(encoding="utf-8"))
    entries = raw["sources"] if isinstance(raw, dict) else raw
    specs = [SourceSpec(**entry) for entry in entries]
    names = [s.name for s in specs]
    if len(names) != len(set(names)):
        raise ValueError("source names must be unique")
    return specs


def _resolve(spec: SourceSpec, base_dir: Path | None) -> list[Path]:
    pattern = spec.path
    if base_dir is not None and not Path(pattern).is_absolute():
        pattern = str(base_dir / pattern)
    if Path(pattern).is_dir():
        suffix = {"txt": "*.txt", "jsonl": "*.jsonl*", "parquet": "*.parquet"}[spec.type]
        files = sorted(Path(pattern).rglob(suffix))
    else:
        files = sorted(Path(p) for p in glob.glob(pattern, recursive=True))
    if not files:
        raise FileNotFoundError(f"{spec.name}: no files match {pattern}")
    return files


def _open_text(path: Path):
    if path.suffix == ".gz":
        return io.TextIOWrapper(gzip.open(path, "rb"), encoding="utf-8")
    return open(path, encoding="utf-8")


def iter_documents(spec: SourceSpec, base_dir: Path | None = None) -> Iterator[dict]:
    """Yield ``{"text", "doc_id"}`` records, raw (normalization happens later)."""
    produced = 0
    for path in _resolve(spec, base_dir):
        rel = Path(os.path.relpath(path, base_dir or Path.cwd())).as_posix()
        for index, (doc_id, text) in enumerate(_iter_file(spec, path, rel)):
            yield {"text": text, "doc_id": doc_id or f"{rel}#{index}"}
            produced += 1
            if spec.max_docs is not None and produced >= spec.max_docs:
                return


def _iter_file(spec: SourceSpec, path: Path, rel: str) -> Iterator[tuple[str | None, str]]:
    if spec.type == "txt":
        text = path.read_text(encoding="utf-8", errors="replace")
        if spec.doc_split == "file":
            yield rel, text
        elif spec.doc_split == "paragraph":
            for i, para in enumerate(text.replace("\r\n", "\n").split("\n\n")):
                yield f"{rel}#p{i}", para
        else:
            for i, line in enumerate(text.splitlines()):
                yield f"{rel}#l{i}", line
    elif spec.type == "jsonl":
        with _open_text(path) as handle:
            for line_no, line in enumerate(handle):
                if not line.strip():
                    continue
                record = json.loads(line)
                text = record.get(spec.text_field)
                if not isinstance(text, str):
                    continue
                doc_id = str(record[spec.id_field]) if spec.id_field and spec.id_field in record else None
                yield doc_id or f"{rel}:{line_no}", text
    else:
        try:
            import pyarrow.parquet as pq
        except ImportError as exc:  # pragma: no cover - optional dependency
            raise ImportError("parquet sources need `pip install pyarrow`") from exc
        parquet = pq.ParquetFile(path)
        columns = [spec.text_field] + ([spec.id_field] if spec.id_field else [])
        row = 0
        for batch in parquet.iter_batches(columns=columns, batch_size=4096):
            texts = batch.column(spec.text_field).to_pylist()
            ids = batch.column(spec.id_field).to_pylist() if spec.id_field else [None] * len(texts)
            for doc_id, text in zip(ids, texts):
                if isinstance(text, str):
                    yield (str(doc_id) if doc_id is not None else f"{rel}:{row}"), text
                row += 1
