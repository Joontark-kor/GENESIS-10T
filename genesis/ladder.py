"""Scaling ladder: plan a set of runs, then fit loss against model size.

    # 1) write runs/ladder/plan.json and run_ladder.sh (prints GPU-hour estimates)
    python -m genesis.ladder plan --data data/tokens/ko32k-v1 \
        --configs configs/dense-40m.json configs/dense-100m.json configs/dense-300m.json \
        configs/moe-8x-100m-active.json --gpus 1

    # 2) bash runs/ladder/run_ladder.sh      (on the GPU machine)

    # 3) table + power-law fit + plot, and a prediction for a larger model
    python -m genesis.ladder report --runs runs/ladder --predict configs/dense-1b.json

Each run gets min(tokens_per_param x params, max_epochs x train tokens) tokens,
so small models are compute-matched by the same rule and nothing is repeated
more than ``max_epochs`` times. The fit is ``bpb(N) = E + A * N^-alpha`` over
non-embedding parameters N of the *dense* runs; MoE runs are listed beside it
for the dense-vs-MoE comparison at equal active size.
"""
from __future__ import annotations

import argparse
import json
import math
from pathlib import Path
import shlex

import numpy as np

from .config import ModelConfig
from .data.shards import read_manifest
from .estimate import estimate, training_flops


# --------------------------------------------------------------------------- plan

def plan_runs(data: Path, configs: list[Path], tokens_per_param: float = 20.0, max_epochs: float = 4.0,
              batch_size: int = 16, grad_accum: int = 4, gpus: int = 1, lr: float = 6e-4,
              lr_overrides: dict[str, float] | None = None, out_root: Path = Path("runs/ladder"),
              gpu_tflops: float = 989.0, mfu: float = 0.35) -> dict:
    train_tokens = read_manifest(data)["splits"]["train"]["tokens"]
    runs = []
    for path in configs:
        config = ModelConfig.from_json(path)
        counts = estimate(config)
        tokens_per_step = batch_size * grad_accum * config.context_length * gpus
        budget = min(tokens_per_param * counts["total_parameters"], max_epochs * train_tokens)
        steps = max(1, math.ceil(budget / tokens_per_step))
        tokens = steps * tokens_per_step
        flops = training_flops(config, tokens)
        name = path.stem
        run_lr = (lr_overrides or {}).get(name, lr)
        out_dir = out_root / name
        launcher = (["torchrun", "--standalone", f"--nproc_per_node={gpus}", "-m", "genesis.train"]
                    if gpus > 1 else ["python", "-m", "genesis.train"])
        command = launcher + [
            "--config", str(path), "--data", str(data), "--out-dir", str(out_dir),
            "--batch-size", str(batch_size), "--grad-accum", str(grad_accum), "--steps", str(steps),
            "--lr", str(run_lr), "--eval-every", str(max(50, steps // 20)),
            "--save-every", str(max(100, steps // 10)), "--peak-tflops", str(gpu_tflops)]
        runs.append({
            "name": name, "config": str(path), "out_dir": str(out_dir), "moe": config.is_moe,
            "parameters": counts["total_parameters"],
            "non_embedding_active_parameters": counts["non_embedding_active_parameters"],
            "tokens": tokens, "epochs": tokens / train_tokens, "steps": steps, "lr": run_lr,
            "training_flops": flops,
            "estimated_gpu_hours": flops / (gpu_tflops * 1e12 * mfu) / 3600,
            "command": " ".join(shlex.quote(c) for c in command),
        })
    return {"data": str(data), "train_tokens": train_tokens, "tokens_per_param": tokens_per_param,
            "max_epochs": max_epochs, "assumed_mfu": mfu, "gpu_tflops": gpu_tflops, "gpus": gpus,
            "runs": runs,
            "total_estimated_gpu_hours": sum(r["estimated_gpu_hours"] for r in runs)}


def write_plan(plan: dict, out_root: Path) -> Path:
    out_root.mkdir(parents=True, exist_ok=True)
    (out_root / "plan.json").write_text(json.dumps(plan, ensure_ascii=False, indent=2), encoding="utf-8")
    lines = ["#!/usr/bin/env bash", "# generated by genesis.ladder plan; re-running resumes finished-or-partial runs",
             "set -euo pipefail"]
    for run in plan["runs"]:
        lines += [f"echo '=== {run['name']} ({run['steps']} steps) ==='",
                  f"if [ -f {run['out_dir']}/ckpt_last.pt ]; then {run['command']} --resume; "
                  f"else {run['command']}; fi"]
    script = out_root / "run_ladder.sh"
    script.write_text("\n".join(lines) + "\n", encoding="utf-8")
    script.chmod(0o755)
    return script


# --------------------------------------------------------------------------- report

def load_run(run_dir: Path) -> dict | None:
    info_path, metrics_path = run_dir / "run.json", run_dir / "metrics.jsonl"
    if not info_path.exists() or not metrics_path.exists():
        return None
    info = json.loads(info_path.read_text(encoding="utf-8"))
    records = [json.loads(line) for line in metrics_path.read_text(encoding="utf-8").splitlines() if line.strip()]
    evals = [r for r in records if r["type"] == "eval"]
    trains = [r for r in records if r["type"] == "train"]
    if not evals:
        return None
    last = evals[-1]
    return {
        "name": run_dir.name, "moe": info["config"]["n_experts"] > 1,
        "parameters": info["parameters"], "N": info["non_embedding_active_parameters"],
        "step": last["step"], "planned_steps": info["steps"],
        "finished": last["step"] >= info["steps"],
        "tokens": last["step"] * info["tokens_per_step"],
        "val_bpb": last["bpb"], "val_loss": last["loss"],
        "mean_tokens_per_s": float(np.mean([r["tokens_per_s"] for r in trains])) if trains else None,
        "mean_mfu": float(np.mean([r["mfu"] for r in trains if "mfu" in r])) if any("mfu" in r for r in trains) else None,
    }


def fit_power_law(sizes: list[float], losses: list[float]) -> dict:
    """Fit ``loss = E + A * N^-alpha`` by scanning E and regressing log(loss - E) on log N."""
    n = np.asarray(sizes, dtype=float)
    y = np.asarray(losses, dtype=float)
    if len(n) < 3:
        raise ValueError("need at least 3 dense runs to fit a power law with an offset")
    best = None
    for e in np.linspace(0.0, y.min() * 0.999, 400):
        slope, intercept = np.polyfit(np.log(n), np.log(y - e), 1)
        pred = e + np.exp(intercept) * n ** slope
        err = float(np.mean((np.log(pred) - np.log(y)) ** 2))
        if slope < 0 and (best is None or err < best[0]):
            best = (err, e, math.exp(intercept), -slope)
    if best is None:
        raise ValueError("loss does not decrease with size; check the runs")
    err, e, a, alpha = best
    return {"E": e, "A": a, "alpha": alpha, "rms_log_error": math.sqrt(err)}


def predict(fit: dict, n: float) -> float:
    return fit["E"] + fit["A"] * n ** -fit["alpha"]


def report(runs_root: Path, predict_configs: list[Path] | None = None, plot: Path | None = None) -> dict:
    runs = [r for d in sorted(p for p in runs_root.iterdir() if p.is_dir()) if (r := load_run(d))]
    if not runs:
        raise ValueError(f"no finished evaluations under {runs_root}")
    dense = sorted((r for r in runs if not r["moe"]), key=lambda r: r["N"])
    result: dict = {"runs": runs}
    if len(dense) >= 3:
        fit = fit_power_law([r["N"] for r in dense], [r["val_bpb"] for r in dense])
        result["fit"] = fit
        for r in runs:
            r["dense_fit_bpb_at_same_N"] = predict(fit, r["N"])
        result["predictions"] = []
        for path in predict_configs or []:
            config = ModelConfig.from_json(path)
            n = estimate(config)["non_embedding_active_parameters"]
            result["predictions"].append({"config": str(path), "N": n, "predicted_val_bpb": predict(fit, n)})
    if plot is not None:
        _plot(runs, result.get("fit"), plot)
        result["plot"] = str(plot)
    return result


def _plot(runs: list[dict], fit: dict | None, path: Path) -> None:
    try:
        import matplotlib
        matplotlib.use("Agg")
        import matplotlib.pyplot as plt
    except ImportError:  # pragma: no cover - optional
        print("matplotlib not installed; skipping plot")
        return
    fig, ax = plt.subplots(figsize=(6, 4), dpi=150)
    dense = [r for r in runs if not r["moe"]]
    moe = [r for r in runs if r["moe"]]
    ax.scatter([r["N"] for r in dense], [r["val_bpb"] for r in dense], color="#1f6feb", label="dense", zorder=3)
    if moe:
        ax.scatter([r["N"] for r in moe], [r["val_bpb"] for r in moe], color="#d97706", marker="D",
                   label="MoE (active N)", zorder=3)
    for r in runs:
        ax.annotate(r["name"], (r["N"], r["val_bpb"]), textcoords="offset points", xytext=(5, 5), fontsize=7)
    if fit:
        xs = np.geomspace(min(r["N"] for r in runs) / 2, max(r["N"] for r in runs) * 20, 100)
        ax.plot(xs, [predict(fit, x) for x in xs], color="#6e7781", linestyle="--",
                label=f"fit: {fit['E']:.3f} + {fit['A']:.2f}·N^-{fit['alpha']:.3f}")
    ax.set_xscale("log")
    ax.set_xlabel("non-embedding active parameters N")
    ax.set_ylabel("validation bits per byte")
    ax.grid(True, which="both", alpha=0.25)
    ax.legend(fontsize=8, frameon=False)
    fig.tight_layout()
    path.parent.mkdir(parents=True, exist_ok=True)
    fig.savefig(path)
    plt.close(fig)


def _human(n: float) -> str:
    return f"{n/1e9:.2f}B" if n >= 1e9 else f"{n/1e6:.1f}M"


def _table(rows: list[dict]) -> str:
    header = "| run | params | non-emb N | tokens | val bpb | dense fit at N | tok/s | MFU | finished |"
    out = [header, "|---|---:|---:|---:|---:|---:|---:|---:|---|"]
    for r in rows:
        fit_value = f"{r['dense_fit_bpb_at_same_N']:.4f}" if "dense_fit_bpb_at_same_N" in r else ""
        tps = f"{r['mean_tokens_per_s']:,.0f}" if r["mean_tokens_per_s"] else ""
        mfu = f"{r['mean_mfu']:.1%}" if r["mean_mfu"] is not None else ""
        out.append(f"| {r['name']} | {r['parameters']/1e6:.1f}M | {r['N']/1e6:.1f}M | {_human(r['tokens'])} | "
                   f"{r['val_bpb']:.4f} | {fit_value} | {tps} | {mfu} | {'yes' if r['finished'] else 'no'} |")
    return "\n".join(out)


def main() -> None:
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = p.add_subparsers(dest="command", required=True)
    pl = sub.add_parser("plan")
    pl.add_argument("--data", type=Path, required=True)
    pl.add_argument("--configs", type=Path, nargs="+", required=True)
    pl.add_argument("--tokens-per-param", type=float, default=20.0)
    pl.add_argument("--max-epochs", type=float, default=4.0)
    pl.add_argument("--batch-size", type=int, default=16)
    pl.add_argument("--grad-accum", type=int, default=4)
    pl.add_argument("--gpus", type=int, default=1)
    pl.add_argument("--lr", type=float, default=6e-4)
    pl.add_argument("--lr-for", nargs="*", default=[], metavar="NAME=LR",
                    help="per-config learning rates, e.g. dense-40m=1e-3")
    pl.add_argument("--gpu-tflops", type=float, default=989.0)
    pl.add_argument("--mfu", type=float, default=0.35)
    pl.add_argument("--out", type=Path, default=Path("runs/ladder"))
    rp = sub.add_parser("report")
    rp.add_argument("--runs", type=Path, default=Path("runs/ladder"))
    rp.add_argument("--predict", type=Path, nargs="*", default=[])
    rp.add_argument("--plot", type=Path, default=None, help="PNG path (default: <runs>/ladder.png)")
    rp.add_argument("--json", type=Path, default=None)
    args = p.parse_args()

    if args.command == "plan":
        overrides = {k: float(v) for k, v in (item.split("=", 1) for item in args.lr_for)}
        plan = plan_runs(args.data, args.configs, args.tokens_per_param, args.max_epochs, args.batch_size,
                         args.grad_accum, args.gpus, args.lr, overrides, args.out, args.gpu_tflops, args.mfu)
        script = write_plan(plan, args.out)
        print(f"train tokens available: {plan['train_tokens']:,}")
        print("| run | params | tokens | epochs | steps | est. GPU-hours | est. wall hours |")
        print("|---|---:|---:|---:|---:|---:|---:|")
        for r in plan["runs"]:
            print(f"| {r['name']} | {r['parameters']/1e6:.1f}M | {_human(r['tokens'])} | {r['epochs']:.2f} | "
                  f"{r['steps']:,} | {r['estimated_gpu_hours']:.1f} | {r['estimated_gpu_hours'] / plan['gpus']:.1f} |")
        print(f"total ≈ {plan['total_estimated_gpu_hours']:.1f} GPU-hours at {plan['assumed_mfu']:.0%} MFU "
              f"on {plan['gpus']} GPU(s)")
        print(f"run with: bash {script}")
    else:
        plot = args.plot or args.runs / "ladder.png"
        result = report(args.runs, args.predict, plot)
        print(_table(result["runs"]))
        if "fit" in result:
            f = result["fit"]
            print(f"\nfit (dense): bpb = {f['E']:.4f} + {f['A']:.3f} * N^-{f['alpha']:.4f}  "
                  f"(rms log error {f['rms_log_error']:.4f})")
            for pred in result["predictions"]:
                print(f"predicted {pred['config']}: N={pred['N']/1e6:.0f}M -> val bpb ≈ {pred['predicted_val_bpb']:.4f}")
        else:
            print("\n(need 3+ finished dense runs for a fit)")
        if args.json:
            args.json.write_text(json.dumps(result, ensure_ascii=False, indent=2), encoding="utf-8")


if __name__ == "__main__":
    main()
